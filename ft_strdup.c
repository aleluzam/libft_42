#include "libft.h"

static char	*ft_strcpy(char *dest, char *src)
{
	int	i;

	i = 0;
	while (src[i])
	{
		dest[i] = src[i];
		i++;
	}
	dest[i] = '\0';
	return (dest);
}

char	*ft_strdup(const char *src)
{
	char	*new;

	new = malloc((ft_strlen(src) + 1) * sizeof(char));
	if (!new)
		return (NULL);
	return (ft_strcpy(new, (char *)src));
}
